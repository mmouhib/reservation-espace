"use client";

import { Serwist } from "@serwist/window";
import { createContext, useCallback, useContext, useEffect, useMemo, useRef, useState, type ReactNode } from "react";

interface BeforeInstallPromptEvent extends Event {
  prompt(): Promise<void>;
  userChoice: Promise<{ outcome: "accepted" | "dismissed" }>;
}

interface PwaContextValue {
  /** A new service worker is installed and waiting to take over. */
  updateAvailable: boolean;
  applyUpdate: () => void;
  dismissUpdate: () => void;
  /** Chromium exposed an install prompt (beforeinstallprompt). */
  canPromptInstall: boolean;
  promptInstall: () => Promise<void>;
  /** iOS Safari: no install prompt, the user must use Share → Add to Home Screen. */
  isIos: boolean;
  isStandalone: boolean;
  installDismissed: boolean;
  dismissInstall: () => void;
}

const PwaContext = createContext<PwaContextValue | null>(null);

const DISMISS_KEY = "install-dismissed-at";
const DISMISS_MS = 30 * 24 * 3600 * 1000;
const UPDATE_CHECK_MS = 60 * 60 * 1000;

function readDismissed(): boolean {
  try {
    const at = Number(localStorage.getItem(DISMISS_KEY));
    return !!at && Date.now() - at < DISMISS_MS;
  } catch {
    return false;
  }
}

export function PwaProvider({ children }: { children: ReactNode }) {
  const serwist = useRef<Serwist | null>(null);
  const reloadRequested = useRef(false);
  const deferredPrompt = useRef<BeforeInstallPromptEvent | null>(null);

  const [updateAvailable, setUpdateAvailable] = useState(false);
  const [canPromptInstall, setCanPromptInstall] = useState(false);
  const [isIos, setIsIos] = useState(false);
  const [isStandalone, setIsStandalone] = useState(false);
  const [installDismissed, setInstallDismissed] = useState(true);

  // Service worker registration and update flow.
  useEffect(() => {
    // The SW is only generated by production builds (see next.config.ts).
    if (process.env.NODE_ENV !== "production" || !("serviceWorker" in navigator)) return;

    const sw = new Serwist("/sw.js", { scope: "/", type: "classic" });
    sw.addEventListener("waiting", () => setUpdateAvailable(true));
    sw.addEventListener("controlling", () => {
      if (reloadRequested.current) window.location.reload();
    });
    void sw.register();
    serwist.current = sw;

    const check = () => {
      if (document.visibilityState === "visible") void sw.update();
    };
    const interval = window.setInterval(check, UPDATE_CHECK_MS);
    document.addEventListener("visibilitychange", check);
    return () => {
      window.clearInterval(interval);
      document.removeEventListener("visibilitychange", check);
    };
  }, []);

  // Install prompt.
  useEffect(() => {
    const standalone =
      window.matchMedia("(display-mode: standalone)").matches ||
      (navigator as Navigator & { standalone?: boolean }).standalone === true;
    const ios =
      /iphone|ipad|ipod/i.test(navigator.userAgent) ||
      (navigator.platform === "MacIntel" && navigator.maxTouchPoints > 1);
    /* eslint-disable react-hooks/set-state-in-effect -- browser-only values, unknown during prerender */
    setIsStandalone(standalone);
    setIsIos(ios && !standalone);
    setInstallDismissed(readDismissed());
    /* eslint-enable react-hooks/set-state-in-effect */

    const onPrompt = (e: Event) => {
      e.preventDefault();
      deferredPrompt.current = e as BeforeInstallPromptEvent;
      setCanPromptInstall(true);
    };
    const onInstalled = () => {
      deferredPrompt.current = null;
      setCanPromptInstall(false);
      setIsStandalone(true);
    };
    window.addEventListener("beforeinstallprompt", onPrompt);
    window.addEventListener("appinstalled", onInstalled);
    return () => {
      window.removeEventListener("beforeinstallprompt", onPrompt);
      window.removeEventListener("appinstalled", onInstalled);
    };
  }, []);

  const applyUpdate = useCallback(() => {
    reloadRequested.current = true;
    serwist.current?.messageSkipWaiting();
  }, []);

  const dismissUpdate = useCallback(() => setUpdateAvailable(false), []);

  const promptInstall = useCallback(async () => {
    const prompt = deferredPrompt.current;
    if (!prompt) return;
    await prompt.prompt();
    await prompt.userChoice;
    deferredPrompt.current = null;
    setCanPromptInstall(false);
  }, []);

  const dismissInstall = useCallback(() => {
    try {
      localStorage.setItem(DISMISS_KEY, String(Date.now()));
    } catch {
      // Storage unavailable: dismissal only lasts for this page view.
    }
    setInstallDismissed(true);
  }, []);

  const value = useMemo<PwaContextValue>(
    () => ({
      updateAvailable,
      applyUpdate,
      dismissUpdate,
      canPromptInstall,
      promptInstall,
      isIos,
      isStandalone,
      installDismissed,
      dismissInstall,
    }),
    [updateAvailable, applyUpdate, dismissUpdate, canPromptInstall, promptInstall, isIos, isStandalone, installDismissed, dismissInstall],
  );

  return <PwaContext.Provider value={value}>{children}</PwaContext.Provider>;
}

export function usePwa(): PwaContextValue {
  const ctx = useContext(PwaContext);
  if (!ctx) throw new Error("usePwa must be used inside <PwaProvider>");
  return ctx;
}
